-- ============================================================
--  Сообщения от тренера спортсмену
-- ============================================================
--  В кабинете тренера есть карточка спортсмена с формой «Написать».
--  По умолчанию notifications разрешает insert только администратору
--  и только письма администратору. Здесь открываем третью возможность:
--  тренер пишет спортсмену, который записан на его тренировку.
--
--  Проверка идёт через public.teaches(): она сверяет trainer_id тренера
--  с тренировкой или выбранным тренером в записи. Чужому спортсмену
--  написать нельзя.
--
--  Применить: Supabase → SQL Editor → вставить и запустить.
-- ============================================================

drop policy if exists "notifications: тренер пишет своему спортсмену"
  on public.notifications;

create policy "notifications: тренер пишет своему спортсмену"
  on public.notifications
  for insert with check (
    public.is_trainer()
    and public.teaches(user_id)
  );
