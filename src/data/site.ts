/** Хлебные крошки и заголовок hero страницы направления */
export function directionHeroTitle(name: string, city: string): string {
  return `${name.toUpperCase()} В ${city.toUpperCase()}`;
}

/**
 * Форматы занятий. Считаются по реальным тренировкам направления:
 * level и тип занятия решают, в какую корзину попасть.
 */
export function formatOf(level: string, name: string): FormatKey {
  const haystack = `${level} ${name}`.toLowerCase();
  if (haystack.includes('кемп') || haystack.includes('сбор') || haystack.includes('выезд')) return 'camp';
  if (haystack.includes('персона') || haystack.includes('индивиду')) return 'individual';
  if (haystack.includes('школ') || haystack.includes('начинающ') || haystack.includes('с нуля')) return 'school';
  return 'club';
}

